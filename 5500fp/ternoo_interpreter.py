#!/usr/bin/env python3
"""
TernOO Word Interpreter  v0.2.1
================================
Executes TernOO word programs generated by FlowCode.

The interpreter bridges the gap between:
  FlowCode (generates MAP/UDP/EXEC word sequences)
  5500FP emulator (executes raw ISA instructions)

It operates at the TernOO word level — above the ISA but below Python.
Each word is dispatched by its primary type:

  EXEC word  → follow the edge to the target symbol, call its handler
  MAP word   → record spatial position, pass to renderer if active
  DATA/UDP   → instantiate or update an object, push onto eval stack
  DATA/SCALAR→ push value onto eval stack
  NEURAL     → forward-pass through a neural unit or connection
  I/O        → read/write channel, signal START or END of program
  NULL       → Double Null mechanism — push/pop context

A FlowCode program is a directed graph of symbols (UDP words) connected
by edges (EXEC words), with MAP words encoding each symbol's canvas
position. The interpreter walks the graph from the START symbol,
dispatching each symbol's handler, following EXEC edges as control flow.

Usage:
    from ternoo_interpreter import TernOOInterpreter, load_flowcode
    interp = TernOOInterpreter()
    interp.load_flowcode('myprogram.json')
    interp.run()

Or run directly:
    python3 ternoo_interpreter.py myprogram.json
    python3 ternoo_interpreter.py --demo
"""

