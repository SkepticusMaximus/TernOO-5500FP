# ── I/O Subclass Matrix ──────────────────────────────────────────────────
# Added: 31 May 2026, Adelaide | Author: Stevo + Claude
# T21: -1=file  0=stream  +1=prompt | T20: -1=read  0=bidir  +1=write
IO_CH_FILE, IO_CH_STREAM, IO_CH_PROMPT = -1, 0, +1
IO_OP_READ, IO_OP_BIDIR,  IO_OP_WRITE  = -1, 0, +1

def io_subclass(node) -> tuple:
    """Detect (T21,T20) from label keywords. Bootstrap until palette exposes trits."""
    words = set(node.label.upper().replace('-',' ').replace('_',' ').split())
    write_h = {'OUTPUT','PRINT','SHOW','DISPLAY','MESSAGE','RESULT',
               'ACCEPT','UNDER','PASS','FAIL','TELL','SAY','RESPOND'}
    read_h  = {'INPUT','GET','READ','PROMPT','ASK','ENTER','FETCH'}
    file_h  = {'FILE','LOAD','SAVE','OPEN','WRITE','APPEND','LOG'}
    stream_h= {'SEND','RECV','RECEIVE','NETWORK','STREAM','PIPE'}
    ch = IO_CH_PROMPT
    op = IO_OP_READ
    if words & file_h:    ch = IO_CH_FILE
    elif words & stream_h: ch = IO_CH_STREAM
    if words & write_h:   op = IO_OP_WRITE
    elif words & read_h:  op = IO_OP_READ
    return ch, op

