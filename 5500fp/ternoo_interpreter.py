def demo_loop():
    """Loop: count from 0 to 3 using a cyclic graph."""
    print(f"\n{'='*56}")
    print("DEMO 3: Loop (counter 0→3)")
    print(f"{'='*56}")

    data = {
        'symbols': [
            {'id':1,'kind':'io',       'x':200,'y':80,  'label':'START'},
            {'id':2,'kind':'process',  'x':200,'y':200, 'label':'INCREMENT'},
            {'id':3,'kind':'decision', 'x':200,'y':320, 'label':'DONE?'},
            {'id':4,'kind':'io',       'x':200,'y':440, 'label':'END'},
        ],
        'edges': [
            {'src':1,'dst':2},
            {'src':2,'dst':3},
            {'src':3,'dst':2,'condition':'FALSE'},   # loop back
            {'src':3,'dst':4,'condition':'TRUE'},    # exit
        ]
    }

    interp = TernOOInterpreter(trace=True)
    interp.set_env('counter', 0)
    interp.set_env('limit',   3)

    def increment(n, out, stack, env):
        env['counter'] += 1
        print(f"    [INCREMENT] counter = {env['counter']}")
        return env['counter']

    def done_check(n, outgoing, stack, env):
        """Decision handler signature: (node, outgoing_list, stack, env)"""
        val = env['counter'] >= env['limit']
        result = +1 if val else -1
        print(f"    [DONE?] counter={env['counter']} "
              f"limit={env['limit']} → {'DONE (+)' if val else 'CONTINUE (−)'}")
        stack.append(result)
        # Return edge index: 0=first outgoing (FALSE=loop back), 1=second (TRUE=exit)
        # edges are: [0]=FALSE(loop), [1]=TRUE(exit)
        return 1 if val else 0

    interp.register_handler('INCREMENT', increment)
    # Decision handlers take (node, outgoing_list, stack, env)
    interp.handlers['DONE?'] = done_check

    interp.load_dict(data)
    result = interp.run()
    print(f"\nResult: steps={result['steps']} "
          f"counter={result['env']['counter']}")


